BEGIN;
CREATE SCHEMA IF NOT EXISTS farmacia;
SET LOCAL search_path = farmacia, pg_catalog;

CREATE FUNCTION normalizar_texto(text) RETURNS text
LANGUAGE sql IMMUTABLE STRICT PARALLEL SAFE
SET search_path = pg_catalog
AS $$ SELECT lower(translate($1, 'ÁÉÍÓÚÜÑáéíóúüñ', 'AEIOUUNaeiouun')) $$;

CREATE TABLE usuario (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  nombres VARCHAR(100) NOT NULL,
  apellido_paterno VARCHAR(100) NOT NULL,
  apellido_materno VARCHAR(100) NULL,
  ci VARCHAR(20) NOT NULL,
  ci_extencion VARCHAR(10) NOT NULL,
  telefono VARCHAR(20) NOT NULL,
  email VARCHAR(255) NOT NULL,
  user_name VARCHAR(100) NOT NULL,
  password_hash VARCHAR(255)   NOT NULL,
  role VARCHAR(20)  NOT NULL DEFAULT 'Bioquimico',
  activo smallint NOT NULL DEFAULT 1,
  must_change_password smallint NOT NULL DEFAULT 1,
  fecha_registro timestamptz NOT NULL DEFAULT CURRENT_TIMESTAMP,
  ultima_actualizacion timestamptz NULL DEFAULT NULL,
  id_usuario INT NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_usuario_editor FOREIGN KEY (id_usuario) REFERENCES usuario(id) ON DELETE NO ACTION ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT ck_usuario_activo CHECK (activo IN (0,1)),
  CONSTRAINT ck_usuario_cambio_password CHECK (must_change_password IN (0,1)),
  CONSTRAINT ck_usuario_rol CHECK (role IN ('Admin','Bioquimico')),
  CONSTRAINT ck_usuario_email CHECK (CHAR_LENGTH(TRIM(email)) > 0),
  CONSTRAINT ck_usuario_nombre_login CHECK (CHAR_LENGTH(TRIM(user_name)) > 0),
  CONSTRAINT ck_usuario_password CHECK (CHAR_LENGTH(password_hash) >= 60)
);

CREATE TABLE usuario_token (
  id integer GENERATED BY DEFAULT AS IDENTITY,
  usuario_idusuario INT NOT NULL,
  token_hash CHAR(64)   NOT NULL,
  tipo_token VARCHAR(45)   NOT NULL,
  fecha_creacion timestamptz NOT NULL,
  fecha_expiracion timestamptz NOT NULL,
  revocado smallint NOT NULL DEFAULT 0,
  usado smallint NOT NULL DEFAULT 0,
  fecha_uso timestamptz NULL,
  fecha_revocacion timestamptz NULL,
  PRIMARY KEY (id),
  CONSTRAINT fk_token_usuario FOREIGN KEY (usuario_idusuario) REFERENCES usuario(id) ON DELETE NO ACTION ON UPDATE NO ACTION DEFERRABLE INITIALLY IMMEDIATE,
  CONSTRAINT ck_token_revocado CHECK (revocado IN (0,1)),
  CONSTRAINT ck_token_usado CHECK (usado IN (0,1)),
  CONSTRAINT ck_token_expiracion CHECK (fecha_expiracion > fecha_creacion),
  CONSTRAINT ck_token_hash CHECK (CHAR_LENGTH(token_hash) = 64),
  CONSTRAINT ck_token_tipo CHECK (CHAR_LENGTH(TRIM(tipo_token)) > 0)
);

CREATE TABLE clasificacion (
  id integer GENERATED BY DEFAULT AS IDENTITY,
