  CONSTRAINT ck_clasificacion_estado CHECK (estado IN (0,1)),
  CONSTRAINT ck_clasificacion_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) BETWEEN 3 AND 45)
);

CREATE TABLE cliente (
