CREATE FUNCTION registrar_auditoria() RETURNS trigger
LANGUAGE plpgsql SECURITY DEFINER SET search_path = pg_catalog, farmacia AS $$
DECLARE
 anterior jsonb; nuevo jsonb; clave jsonb; operacion text := TG_OP;
 actor integer := NULLIF(current_setting('app.usuario_id',true),'')::integer;
 cambio smallint := 0;
BEGIN
 IF TG_OP <> 'INSERT' THEN anterior := to_jsonb(OLD); END IF;
 IF TG_OP <> 'DELETE' THEN nuevo := to_jsonb(NEW); END IF;
 IF TG_OP='UPDATE' THEN
   IF coalesce(anterior->>'activo',anterior->>'estado')='1'
      AND coalesce(nuevo->>'activo',nuevo->>'estado')='0' THEN operacion:='BAJA_LOGICA';
   ELSIF coalesce(anterior->>'activo',anterior->>'estado')='0'
      AND coalesce(nuevo->>'activo',nuevo->>'estado')='1' THEN operacion:='REACTIVACION'; END IF;
   IF anterior->>'password_hash' IS DISTINCT FROM nuevo->>'password_hash' THEN cambio:=1; END IF;
 END IF;
 IF TG_TABLE_NAME='detalle_venta' THEN
   clave:=jsonb_build_object('id_venta',coalesce(nuevo,anterior)->'id_venta','id_medicamento',coalesce(nuevo,anterior)->'id_medicamento');
 ELSE clave:=jsonb_build_object('id',coalesce(nuevo,anterior)->'id'); END IF;
 INSERT INTO farmacia.auditoria(tabla,operacion,clave_registro,usuario_app_id,origen_actor,usuario_db,
 conexion_id,solicitud_id,motivo,datos_anteriores,datos_nuevos,credencial_modificada)
 VALUES(TG_TABLE_NAME,operacion,clave,actor,CASE WHEN actor IS NULL THEN 'SIN_CONTEXTO' ELSE 'CONTEXTO_SESION' END,
 session_user,pg_backend_pid(),left(NULLIF(current_setting('app.solicitud_id',true),''),64),
 left(NULLIF(current_setting('app.motivo',true),''),255),
 anterior - 'password_hash' - 'token_hash',nuevo - 'password_hash' - 'token_hash',cambio);
 RETURN NULL;
END $$;
REVOKE ALL ON FUNCTION registrar_auditoria() FROM PUBLIC;

CREATE FUNCTION actualizar_fecha() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN NEW.ultima_actualizacion:=CURRENT_TIMESTAMP; RETURN NEW; END $$;
CREATE FUNCTION impedir_cambio_auditoria() RETURNS trigger
LANGUAGE plpgsql SET search_path=pg_catalog AS $$
BEGIN RAISE EXCEPTION 'El historial de auditoria es inmutable'; END $$;
CREATE TRIGGER tr_auditoria_inmutable BEFORE UPDATE OR DELETE OR TRUNCATE ON auditoria
FOR EACH STATEMENT EXECUTE FUNCTION impedir_cambio_auditoria();
CREATE TRIGGER tr_legacy_inmutable BEFORE UPDATE OR DELETE OR TRUNCATE ON auditoria_legacy_mysql
FOR EACH STATEMENT EXECUTE FUNCTION impedir_cambio_auditoria();

DO $$ DECLARE tabla text; BEGIN
 FOREACH tabla IN ARRAY ARRAY['usuario','usuario_token','cliente','clasificacion','medicamento','venta','detalle_venta'] LOOP
 EXECUTE format('CREATE TRIGGER tr_%I_auditoria AFTER INSERT OR UPDATE OR DELETE ON farmacia.%I FOR EACH ROW EXECUTE FUNCTION farmacia.registrar_auditoria()',tabla,tabla);
 END LOOP;
 FOREACH tabla IN ARRAY ARRAY['usuario','cliente','clasificacion','medicamento','venta'] LOOP
 EXECUTE format('CREATE TRIGGER tr_%I_fecha BEFORE UPDATE ON farmacia.%I FOR EACH ROW EXECUTE FUNCTION farmacia.actualizar_fecha()',tabla,tabla);
 END LOOP;
END $$;

CREATE VIEW vw_auditoria_stock AS
SELECT id AS id_auditoria,fecha_utc,usuario_app_id,motivo,(clave_registro->>'id')::integer AS id_medicamento,
 coalesce((datos_anteriores->>'stock')::integer,0) AS stock_anterior,
 coalesce((datos_nuevos->>'stock')::integer,0) AS stock_nuevo,
 coalesce((datos_nuevos->>'stock')::integer,0)-coalesce((datos_anteriores->>'stock')::integer,0) AS variacion
FROM auditoria WHERE tabla='medicamento' AND operacion<>'DELETE';
CREATE VIEW vw_ventas_descuadradas AS
SELECT v.id,v.total,coalesce(sum(d.cantidad*d.precio_unitario),0) AS total_detalle
FROM venta v LEFT JOIN detalle_venta d ON d.id_venta=v.id
GROUP BY v.id,v.total HAVING v.total<>coalesce(sum(d.cantidad*d.precio_unitario),0);

