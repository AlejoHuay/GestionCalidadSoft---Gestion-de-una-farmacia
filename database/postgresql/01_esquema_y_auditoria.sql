  CONSTRAINT ck_medicamento_stock CHECK (stock >= 0),
  CONSTRAINT ck_medicamento_estado CHECK (estado IN (0,1)),
  CONSTRAINT ck_medicamento_nombre CHECK (CHAR_LENGTH(TRIM(nombre)) BETWEEN 3 AND 100)
);

CREATE TABLE venta (
